import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import pg from 'pg';
process.env.QWEN_STORAGE='postgres';
process.env.DATABASE_URL='postgresql:///qwendirector';
process.env.QWEN_API_AUTOSTART='false';
const {app}=await import('../apps/api/src/index.ts');
const pool=new pg.Pool({host:'/var/run/postgresql',database:'qwendirector'});
const [project,scene,shot,node]=Array.from({length:4},()=>randomUUID());
try {
  await pool.query('insert into projects(id,name) values($1,$2)',[project,'API integration smoke']);
  await pool.query('insert into scenes(id,project_id,title,position) values($1,$2,$3,1)',[scene,project,'test']);
  await pool.query('insert into shots(id,scene_id,title,position) values($1,$2,$3,1)',[shot,scene,'test']);
  await pool.query("insert into nodes(id,instance_id,capabilities,status,heartbeat_at) values($1,'test','{}','online',now())",[node]);
  const body={shotId:shot,planHash:'plan',requestHash:'request',idempotencyKey:'key',adapterId:'llama.cpp',plan:{prompt:'Return exactly E2E_OK'},requiredCapabilities:{}};
  const post=(url,payload)=>app.inject({method:'POST',url,payload});
  const created=await post('/v1/jobs',body); assert.equal(created.statusCode,201,created.body);
  const id=created.json().jobId;
  assert.equal((await pool.query('select state from jobs where id=$1',[id])).rows[0].state,'awaiting_approval');
  assert.equal((await post('/v1/jobs',body)).json().jobId,id);
  assert.equal((await post('/v1/jobs',{...body,planHash:'changed'})).statusCode,409);
  const approved=await post(`/v1/jobs/${id}/approve`,{planHash:'plan',actor:'integration'});
  assert.equal(approved.statusCode,200,approved.body);
  assert.equal((await pool.query('select count(*) from approvals where job_id=$1',[id])).rows[0].count,'1');
  const {PgAttemptRepository}=await import('../apps/api/src/pg-repository.ts');
  const repo=new PgAttemptRepository(pool);
  const attempt=await repo.claim(id,node);
  assert.equal(attempt.adapterId,'llama.cpp');
  assert.equal(attempt.plan.prompt,'Return exactly E2E_OK');
  const heartbeat=await post(`/v1/attempts/${attempt.id}/heartbeat`,{fencingToken:attempt.fencingToken,sequence:1});
  assert.equal(heartbeat.statusCode,200,heartbeat.body);
  const manifest={adapter:'llama.cpp',text:'E2E_OK'};
  const committed=await post(`/v1/attempts/${attempt.id}/commit`,{fencingToken:attempt.fencingToken,manifest});
  assert.equal(committed.statusCode,200,committed.body);
  assert.deepEqual(committed.json().manifest,manifest);
  const savedManifest=await app.inject({method:'GET',url:`/v1/attempts/${attempt.id}/manifest`});
  assert.equal(savedManifest.statusCode,200,savedManifest.body);
  assert.deepEqual(savedManifest.json().manifest,manifest);
  assert.match(savedManifest.json().manifest_hash,/^[a-f0-9]{64}$/);
  assert.equal((await pool.query('select state from jobs where id=$1',[id])).rows[0].state,'succeeded');
  assert.equal((await post(`/v1/jobs/${id}/approve`,{planHash:'plan',actor:'test'})).statusCode,409);
  console.log('OK: API persists jobs/approval, rejects changed payload, awaits heartbeat/commit');
} finally {
  await pool.query('delete from approvals where job_id in(select id from jobs where shot_id=$1)',[shot]);
  await pool.query('delete from attempt_manifests where attempt_id in(select id from attempts where job_id in(select id from jobs where shot_id=$1))',[shot]);
  await pool.query('delete from attempts where job_id in(select id from jobs where shot_id=$1)',[shot]);
  await pool.query('delete from jobs where shot_id=$1',[shot]);
  await pool.query('delete from nodes where id=$1',[node]);
  await pool.query('delete from shots where id=$1',[shot]);
  await pool.query('delete from scenes where id=$1',[scene]);
  await pool.query('delete from projects where id=$1',[project]);
  await pool.end(); await app.close();
}
